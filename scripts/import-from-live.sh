#!/usr/bin/env bash
#
# import-from-live.sh - write the catalogue from what the organisation actually
# is. Phase A records reality, drift and all, so that the first `tofu plan`
# reports no changes. Running it again after phase B has begun would undo that
# work, so it refuses unless you pass --force.
#
# Usage:
#   ./scripts/import-from-live.sh            # write repos/, teams/, people/
#   ./scripts/import-from-live.sh --force    # overwrite an existing catalogue
#
# Requires: gh (authenticated), jq.

set -euo pipefail

ORG="${ORG:-Nano-Collective}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ "$FORCE" -eq 0 ] && [ -n "$(ls -A "$ROOT/repos" 2>/dev/null)" ]; then
  echo "error: $ROOT/repos is not empty. Pass --force to overwrite." >&2
  exit 1
fi

# Repos whose whitepaper slug differs from the repo name, or which predate the
# whitepaper pipeline entirely. Everything not listed here must either match a
# slug in the docs manifest or carry a whitepaper_exempt reason.
exempt_reason() {
  case "$1" in
    .github|infrastructure) echo "infrastructure" ;;
    docs|organisation|branding) echo "infrastructure" ;;
    taskforest|contentforest|roster|docforest) echo "predates-pipeline" ;;
    nanocoder|nanotune|nanolist) echo "predates-pipeline" ;;
    get-md|json-up|prompt-scrubber) echo "fast-path" ;;
    *) echo "" ;;
  esac
}

whitepaper_slug() {
  case "$1" in
    sentinel) echo "sentinel" ;;
    nanoterm) echo "nanoterm" ;;
    *) echo "" ;;
  esac
}

echo "Reading $ORG ..."
gh api "orgs/$ORG" > "$WORK/org.json"
gh repo list "$ORG" --limit 200 --json name --jq '.[].name' | sort > "$WORK/repos.txt"

# ------------------------------------------------------------------ repos --

while read -r repo; do
  gh api "repos/$ORG/$repo" > "$WORK/r.json"
  # 204 means enabled, 404 means not. There is no field for it on the repo object.
  if gh api "repos/$ORG/$repo/vulnerability-alerts" >/dev/null 2>&1; then VULN=true; else VULN=false; fi
  gh api "repos/$ORG/$repo/rulesets" > "$WORK/rsindex.json" 2>/dev/null || echo '[]' > "$WORK/rsindex.json"

  echo '[]' > "$WORK/rs.json"
  jq -r '.[]?.id // empty' "$WORK/rsindex.json" | while read -r id; do
    gh api "repos/$ORG/$repo/rulesets/$id" >> "$WORK/rs.ndjson"
  done
  if [ -s "${WORK}/rs.ndjson" ]; then
    jq -s 'sort_by(.name)' "$WORK/rs.ndjson" > "$WORK/rs.json"
    rm -f "$WORK/rs.ndjson"
  fi

  wp="$(whitepaper_slug "$repo")"
  ex="$(exempt_reason "$repo")"

  out="$ROOT/repos/${repo#.}.yaml"
  [ "$repo" = ".github" ] && out="$ROOT/repos/dot-github.yaml"

  REPO="$repo" WP="$wp" EX="$ex" VULN="$VULN" jq -r -f /dev/stdin "$WORK/r.json" > "$out" <<'JQ'
def q: tostring | gsub("\""; "\\\"");
def yn: if . then "true" else "false" end;
[
  "# Generated by scripts/import-from-live.sh. Phase A: this records what the",
  "# organisation is today, including drift. Change it in a pull request.",
  "name: \(env.REPO)",
  if (.description // "") == "" then "description: null" else "description: \"\(.description|q)\"" end,
  if (.homepage // "") == "" then "homepage: null" else "homepage: \"\(.homepage|q)\"" end,
  "visibility: \(.visibility)",
  "archived: \(.archived|yn)",
  "vulnerability_alerts: \(env.VULN)",
  "default_branch: \(.default_branch)",
  "",
  if ((.topics//[])|length) == 0 then "topics: []" else "topics:\n" + ((.topics|sort|map("  - \(.)"))|join("\n")) end,
  "",
  "features:",
  "  issues: \(.has_issues|yn)",
  "  projects: \(.has_projects|yn)",
  "  wiki: \(.has_wiki|yn)",
  "  discussions: \(.has_discussions|yn)",
  "",
  "merge:",
  "  squash: \(.allow_squash_merge|yn)",
  "  merge_commit: \(.allow_merge_commit|yn)",
  "  rebase: \(.allow_rebase_merge|yn)",
  "  auto_merge: \(.allow_auto_merge|yn)",
  "  delete_branch_on_merge: \(.delete_branch_on_merge|yn)",
  ""
] | join("\n")
JQ

  # rulesets, read back from what is live rather than assumed
  {
    if [ "$(jq 'length' "$WORK/rs.json")" = "0" ]; then
      echo "rulesets: {}"
    else
      echo "rulesets:"
      jq -r '
        .[] |
        (if .name == "Quality gates" then "quality"
         elif .name == "Review gates" then "review"
         else ("unknown-" + (.name|ascii_downcase|gsub("[^a-z0-9]+";"-"))) end) as $key |
        "  \($key):",
        "    enforcement: \(.enforcement)",
        (if ([.rules[]|.type] | index("copilot_code_review")) then "    copilot_code_review: true" else empty end)
      ' "$WORK/rs.json"
    fi
    echo ""
    echo "# Labels stay unmanaged until the existing set in this repo has been folded"
    echo "# into org/labels.yaml. Flipping this on before that happens deletes the rest."
    echo "manage_labels: false"
    echo ""
    if [ -n "$wp" ]; then
      echo "whitepaper: $wp"
    else
      echo "whitepaper: null"
      echo "whitepaper_exempt: ${ex:-UNKNOWN}"
    fi
  } >> "$out"

  printf '  %-18s %s\n' "$repo" "$(basename "$out")"
done < "$WORK/repos.txt"

# ------------------------------------------------------------------ teams --

mkdir -p "$ROOT/teams"
gh api "orgs/$ORG/teams" --jq '.[].slug' | while read -r slug; do
  gh api "orgs/$ORG/teams/$slug" > "$WORK/t.json"
  gh api "orgs/$ORG/teams/$slug/repos" --jq '[.[]|{name,role:.role_name}]|sort_by(.name)' > "$WORK/tr.json"
  {
    SLUG="$slug" jq -r '
      "# Generated by scripts/import-from-live.sh.",
      "slug: \(env.SLUG)",
      "name: \"\(.name)\"",
      (if (.description // "") == "" then "description: null" else "description: \"\(.description)\"" end),
      "privacy: \(.privacy)",
      (if .parent then "parent: \(.parent.slug)" else "parent: null" end),
      ""
    ' "$WORK/t.json"
    if [ "$(jq 'length' "$WORK/tr.json")" = "0" ]; then
      echo "# This team grants access to nothing. See the whitepaper."
      echo "repositories: {}"
    else
      echo "repositories:"
      jq -r '.[]|"  \(.name): \(.role)"' "$WORK/tr.json"
    fi
  } > "$ROOT/teams/$slug.yaml"
  printf '  team %-14s %s\n' "$slug" "$slug.yaml"
done

# ----------------------------------------------------------------- people --

mkdir -p "$ROOT/people"
gh api "orgs/$ORG/teams" --jq '.[].slug' > "$WORK/teams.txt"
for role in admin member; do
  gh api "orgs/$ORG/members?role=$role" --jq '.[].login' | while read -r login; do
    orgrole="member"; [ "$role" = "admin" ] && orgrole="owner"
    {
      echo "# Generated by scripts/import-from-live.sh."
      echo "github: $login"
      echo "org_role: $orgrole"
      echo ""
      found=0
      membership=""
      while read -r slug; do
        if gh api "orgs/$ORG/teams/$slug/memberships/$login" >/dev/null 2>&1; then
          r=$(gh api "orgs/$ORG/teams/$slug/memberships/$login" --jq '.role')
          membership="${membership}  - team: ${slug}
    role: ${r}
"
          found=1
        fi
      done < "$WORK/teams.txt"
      if [ "$found" -eq 0 ]; then echo "teams: []"; else echo "teams:"; printf '%s' "$membership"; fi
    } > "$ROOT/people/$login.yaml"
    printf '  person %-12s %s\n' "$login" "$login.yaml"
  done
done

# ---------------------------------------------------------------- import --
#
# Ruleset and team ids are assigned by GitHub, so the import blocks cannot be
# written by hand. They go in a generated tfvars file that imports.tf reads and
# that is committed; see the header of tofu/imports.tf.

: > "$WORK/rulesetids.txt"
while read -r repo; do
  # A private repository answers 403 here, because the Free plan has no
  # rulesets on private repositories. With pipefail that would end the script,
  # so the failure is turned into an empty list.
  { gh api "repos/$ORG/$repo/rulesets" 2>/dev/null || echo '[]'; } \
    | jq -r --arg repo "$repo" '
        if type == "array" then
          .[] | "\($repo):\(if .name == "Quality gates" then "quality" else "review" end)\t\($repo):\(.id)"
        else empty end' >> "$WORK/rulesetids.txt"
done < "$WORK/repos.txt"

gh api "orgs/$ORG/teams" --jq '.[]|"\(.slug)\t\(.id)"' > "$WORK/teamids.txt"

jq -n \
  --rawfile rs "$WORK/rulesetids.txt" \
  --rawfile tm "$WORK/teamids.txt" \
  '
  def pairs($raw):
    ($raw | split("\n") | map(select(length > 0) | split("\t")) | map({key: .[0], value: .[1]}) | from_entries);
  {
    import_ruleset_ids: pairs($rs),
    import_team_ids: pairs($tm)
  }' > "$ROOT/tofu/import-ids.auto.tfvars.json"

jq -e . "$ROOT/tofu/import-ids.auto.tfvars.json" > /dev/null \
  || { echo "error: generated import-ids file is not valid JSON" >&2; exit 1; }

echo
echo "Wrote tofu/import-ids.auto.tfvars.json ($(jq '.import_ruleset_ids|length' "$ROOT/tofu/import-ids.auto.tfvars.json") rulesets, $(jq '.import_team_ids|length' "$ROOT/tofu/import-ids.auto.tfvars.json") teams)"

echo
echo "Done. Now run: tofu -chdir=tofu plan"
echo "It must report no changes before anything is applied."
